    primary = IndigoPrimaryDark,
    onPrimary = IndigoOnPrimaryDark,
    primaryContainer = IndigoPrimaryContainerDark,
    onPrimaryContainer = IndigoOnPrimaryContainerDark,
    secondary = SecondaryTealDark,
    onSecondary = SecondaryOnDark,
    secondaryContainer = SecondaryContainerDark,
    onSecondaryContainer = SecondaryOnContainerDark,
    tertiary = TertiaryAmberDark,
    onTertiary = TertiaryOnDark,
    tertiaryContainer = TertiaryContainerDark,
    onTertiaryContainer = TertiaryOnContainerDark,
    background = BackgroundDark,
    onBackground = OnBackgroundDark,
    surface = SurfaceDark,
    onSurface = OnSurfaceDark,
    surfaceVariant = SurfaceVariantDark,
    onSurfaceVariant = OnSurfaceVariantDark,
    outline = OutlineDark
)

private val LightColorScheme = lightColorScheme(
    primary = IndigoPrimaryLight,
    onPrimary = IndigoOnPrimaryLight,
    primaryContainer = IndigoPrimaryContainerLight,
    onPrimaryContainer = IndigoOnPrimaryContainerLight,
    secondary = SecondaryTealLight,
